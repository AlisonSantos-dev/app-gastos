package dev.alisonsantos.appgastos.divisao;

/**
 * Como a compra é dividida.
 *
 * IGUAL: partes iguais entre as pessoas (os centavos que sobram são distribuídos).
 * VALOR: você diz quanto é de cada um (a soma tem que dar o valor da compra).
 * PERCENTUAL: você diz o percentual de cada um (a soma tem que dar 100).
 */
public enum ModoDivisao {
    IGUAL,
    VALOR,
    PERCENTUAL
}
