-- =====================================================================
-- V5: Legenda de identificação das compras
--
-- Cada regra diz: "quando a compra tiver ESTA característica (CNPJ,
-- estabelecimento, descrição ou MCC), ela é ISTO (descrição amigável,
-- categoria e/ou pessoa)".
-- =====================================================================

CREATE TABLE regra (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_chave       VARCHAR(30)  NOT NULL,
    valor_chave      VARCHAR(255) NOT NULL,
    cartao_final     VARCHAR(4),
    descricao        VARCHAR(255),
    categoria        VARCHAR(60),
    pessoa_id        BIGINT,
    prioridade       INTEGER      NOT NULL DEFAULT 0,
    vigencia_inicio  DATE,
    vigencia_fim     DATE,
    ativa            BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_regra_pessoa FOREIGN KEY (pessoa_id) REFERENCES pessoa (id),
    CONSTRAINT ck_regra_cartao_final CHECK (cartao_final IS NULL OR cartao_final ~ '^[0-9]{4}$'),
    CONSTRAINT ck_regra_vigencia CHECK (vigencia_inicio IS NULL OR vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
    CONSTRAINT ck_regra_resultado CHECK (descricao IS NOT NULL OR categoria IS NOT NULL OR pessoa_id IS NOT NULL)
);

CREATE INDEX idx_regra_ativa ON regra (ativa);

COMMENT ON COLUMN regra.tipo_chave IS 'CNPJ, MERCHANT, DESCRICAO_IGUAL, DESCRICAO_CONTEM ou MCC';
COMMENT ON COLUMN regra.valor_chave IS 'O valor procurado, já normalizado (maiúsculas, sem acento; CNPJ e MCC só com números)';
COMMENT ON COLUMN regra.cartao_final IS 'Opcional: a regra só vale para o cartão com este final';
COMMENT ON COLUMN regra.prioridade IS 'Desempate entre regras do mesmo nível: maior vence';
COMMENT ON COLUMN regra.vigencia_inicio IS 'Opcional: regra temporária, válida a partir desta data';
COMMENT ON COLUMN regra.vigencia_fim IS 'Opcional: regra temporária, válida até esta data';

-- ---------------------------------------------------------------------
-- Transação: qual regra a identificou, e a categoria definida pelo app
-- ---------------------------------------------------------------------
ALTER TABLE transacao ADD COLUMN regra_id BIGINT;
ALTER TABLE transacao ADD COLUMN categoria VARCHAR(60);
ALTER TABLE transacao ADD CONSTRAINT fk_transacao_regra FOREIGN KEY (regra_id) REFERENCES regra (id);

CREATE INDEX idx_transacao_regra ON transacao (regra_id);

COMMENT ON COLUMN transacao.regra_id IS 'A regra da legenda que identificou a transação (vazio se nenhuma)';
COMMENT ON COLUMN transacao.categoria IS 'Categoria definida pelo app (pela legenda), em português';
