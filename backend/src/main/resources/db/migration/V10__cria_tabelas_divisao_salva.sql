-- =====================================================================
-- V10: Divisões salvas
--
-- Uma divisão salva é um "modelo" de divisão com nome, para usar de novo:
-- ex.: "Spotify Família" = 5 pessoas em partes iguais.
-- Ela pode ser aplicada à mão ou por uma regra da legenda, que passa
-- a dividir a compra sozinha todo mês.
-- =====================================================================

CREATE TABLE divisao_salva (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(60)  NOT NULL,
    modo           VARCHAR(20)  NOT NULL,
    ativa          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_divisao_salva_nome UNIQUE (nome),
    -- Valores fixos não servem para um modelo: cada compra tem um valor
    CONSTRAINT ck_divisao_salva_modo CHECK (modo IN ('IGUAL', 'PERCENTUAL'))
);

CREATE TABLE divisao_salva_parte (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    divisao_salva_id  BIGINT        NOT NULL,
    pessoa_id         BIGINT        NOT NULL,
    percentual        NUMERIC(7, 4),
    ordem             INTEGER       NOT NULL,

    CONSTRAINT fk_parte_divisao FOREIGN KEY (divisao_salva_id) REFERENCES divisao_salva (id) ON DELETE CASCADE,
    CONSTRAINT fk_parte_pessoa FOREIGN KEY (pessoa_id) REFERENCES pessoa (id),
    CONSTRAINT ck_parte_percentual CHECK (percentual IS NULL OR (percentual > 0 AND percentual <= 100))
);

CREATE INDEX idx_parte_divisao ON divisao_salva_parte (divisao_salva_id);

COMMENT ON COLUMN divisao_salva_parte.percentual IS 'Só no modo PERCENTUAL (no IGUAL fica vazio)';
COMMENT ON COLUMN divisao_salva_parte.ordem IS 'A ordem das pessoas (decide quem recebe os centavos que sobram)';

-- ---------------------------------------------------------------------
-- Regra: pode dividir a compra, em vez de dar um dono
-- ---------------------------------------------------------------------
ALTER TABLE regra ADD COLUMN divisao_salva_id BIGINT;
ALTER TABLE regra ADD CONSTRAINT fk_regra_divisao_salva FOREIGN KEY (divisao_salva_id) REFERENCES divisao_salva (id);

-- O "pelo menos um resultado" agora inclui a divisão
ALTER TABLE regra DROP CONSTRAINT ck_regra_resultado;
ALTER TABLE regra ADD CONSTRAINT ck_regra_resultado
    CHECK (descricao IS NOT NULL OR categoria IS NOT NULL OR pessoa_id IS NOT NULL OR divisao_salva_id IS NOT NULL);

-- Um dono OU uma divisão, nunca os dois
ALTER TABLE regra ADD CONSTRAINT ck_regra_dono_ou_divisao
    CHECK (pessoa_id IS NULL OR divisao_salva_id IS NULL);
