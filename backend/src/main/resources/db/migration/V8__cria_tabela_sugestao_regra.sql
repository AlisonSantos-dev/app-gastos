-- =====================================================================
-- V8: Sugestões de regras vindas da planilha
--
-- O importador lê a planilha antiga e sugere regras ("quando a descrição
-- contiver X, a compra é Y"). Elas ficam aqui até você aprovar ou
-- descartar. A planilha em si nunca é guardada: só as sugestões.
-- =====================================================================

CREATE TABLE sugestao_regra (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_chave           VARCHAR(30)   NOT NULL,
    valor_chave          VARCHAR(255)  NOT NULL,
    descricao            VARCHAR(255)  NOT NULL,
    pessoa_id            BIGINT,
    secao_planilha       VARCHAR(20),
    compras              INTEGER       NOT NULL,
    confianca_descricao  NUMERIC(5, 2) NOT NULL,
    confianca_pessoa     NUMERIC(5, 2),
    transacoes_afetadas  INTEGER       NOT NULL DEFAULT 0,
    ultima_compra        DATE,
    status               VARCHAR(20)   NOT NULL DEFAULT 'PENDENTE',
    regra_id             BIGINT,
    criado_em            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_sugestao_pessoa FOREIGN KEY (pessoa_id) REFERENCES pessoa (id),
    CONSTRAINT fk_sugestao_regra FOREIGN KEY (regra_id) REFERENCES regra (id)
);

CREATE INDEX idx_sugestao_status ON sugestao_regra (status);

COMMENT ON COLUMN sugestao_regra.compras IS 'Em quantas compras diferentes a planilha usou essa descrição';
COMMENT ON COLUMN sugestao_regra.confianca_descricao IS '% dessas compras em que o nome escrito foi o sugerido';
COMMENT ON COLUMN sugestao_regra.transacoes_afetadas IS 'Quantas transações do app, hoje sem regra, a sugestão identificaria';
COMMENT ON COLUMN sugestao_regra.status IS 'PENDENTE, APROVADA ou DESCARTADA';
