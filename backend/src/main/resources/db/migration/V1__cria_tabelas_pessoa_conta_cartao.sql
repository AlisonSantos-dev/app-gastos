-- =====================================================================
-- V1: Tabelas base do sistema: pessoa, conta e cartão
-- =====================================================================

-- ---------------------------------------------------------------------
-- PESSOA
-- Quem recebe o destino das compras. Pode ser uma pessoa (com ou sem
-- login no app) ou um grupo, como "Contas da casa".
-- ---------------------------------------------------------------------
CREATE TABLE pessoa (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(100) NOT NULL,
    tipo             VARCHAR(20)  NOT NULL DEFAULT 'PESSOA',
    cor              VARCHAR(7),
    nome_no_extrato  VARCHAR(150),
    ativo            BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON COLUMN pessoa.tipo IS 'PESSOA ou GRUPO';
COMMENT ON COLUMN pessoa.cor IS 'Cor de identificação no app, em hexadecimal (ex.: #60A5FA)';
COMMENT ON COLUMN pessoa.nome_no_extrato IS 'Como o nome da pessoa aparece nos Pix recebidos, usado para sugerir recebimentos';

-- ---------------------------------------------------------------------
-- CONTA
-- Uma conta bancária ou uma conta de cartão de crédito vinda da Pluggy.
-- ---------------------------------------------------------------------
CREATE TABLE conta (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pluggy_item_id     VARCHAR(64),
    pluggy_account_id  VARCHAR(64),
    banco              VARCHAR(60)  NOT NULL,
    nome               VARCHAR(100) NOT NULL,
    tipo               VARCHAR(20)  NOT NULL,
    dono_padrao_id     BIGINT,
    ativa              BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_conta_pluggy_account UNIQUE (pluggy_account_id),
    CONSTRAINT fk_conta_dono_padrao FOREIGN KEY (dono_padrao_id) REFERENCES pessoa (id)
);

COMMENT ON COLUMN conta.tipo IS 'CORRENTE ou CARTAO_CREDITO';
COMMENT ON COLUMN conta.dono_padrao_id IS 'Pessoa que recebe por padrão os lançamentos sem cartão (ex.: débito)';

-- ---------------------------------------------------------------------
-- CARTAO
-- Cada cartão (físico, virtual, adicional) de uma conta de cartão.
-- Guarda apenas os 4 últimos dígitos, nunca o número completo.
-- ---------------------------------------------------------------------
CREATE TABLE cartao (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id         BIGINT       NOT NULL,
    ultimos_digitos  VARCHAR(4)   NOT NULL,
    apelido          VARCHAR(60),
    tipo             VARCHAR(20),
    cor              VARCHAR(7),
    modo_dono        VARCHAR(20)  NOT NULL DEFAULT 'FIXO',
    dono_padrao_id   BIGINT,
    status           VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_cartao_conta FOREIGN KEY (conta_id) REFERENCES conta (id),
    CONSTRAINT fk_cartao_dono_padrao FOREIGN KEY (dono_padrao_id) REFERENCES pessoa (id),
    CONSTRAINT uk_cartao_conta_digitos UNIQUE (conta_id, ultimos_digitos),
    CONSTRAINT ck_cartao_ultimos_digitos CHECK (ultimos_digitos ~ '^[0-9]{4}$')
);

COMMENT ON COLUMN cartao.tipo IS 'FISICO ou VIRTUAL (pode ficar vazio até ser definido)';
COMMENT ON COLUMN cartao.modo_dono IS 'FIXO (sempre o dono padrão) ou PERGUNTAR (cartão compartilhado)';
COMMENT ON COLUMN cartao.status IS 'PENDENTE (descoberto pelo sync, aguardando cadastro), ATIVO ou INATIVO';
