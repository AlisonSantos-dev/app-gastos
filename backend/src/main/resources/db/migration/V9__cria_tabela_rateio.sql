-- =====================================================================
-- V9: Divisão de compras entre pessoas
--
-- Uma compra dividida (ex.: o Spotify Família entre 5 pessoas) tem um
-- rateio para cada pessoa, com o valor e o percentual de cada uma.
-- A soma dos valores dos rateios é sempre o valor da transação.
-- =====================================================================

CREATE TABLE rateio (
    id            BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transacao_id  BIGINT         NOT NULL,
    pessoa_id     BIGINT         NOT NULL,
    valor         NUMERIC(14, 2) NOT NULL,
    percentual    NUMERIC(7, 4)  NOT NULL,

    -- Apagou a transação? Os rateios dela vão junto.
    CONSTRAINT fk_rateio_transacao FOREIGN KEY (transacao_id) REFERENCES transacao (id) ON DELETE CASCADE,
    CONSTRAINT fk_rateio_pessoa FOREIGN KEY (pessoa_id) REFERENCES pessoa (id),
    CONSTRAINT ck_rateio_percentual CHECK (percentual > 0 AND percentual <= 100)
);

CREATE INDEX idx_rateio_transacao ON rateio (transacao_id);
CREATE INDEX idx_rateio_pessoa ON rateio (pessoa_id);

COMMENT ON COLUMN rateio.valor IS 'A parte desta pessoa no valor da transação (já com os centavos distribuídos)';
COMMENT ON COLUMN rateio.percentual IS 'A proporção desta pessoa, de 0 a 100. Usada para dividir as outras parcelas da compra';
