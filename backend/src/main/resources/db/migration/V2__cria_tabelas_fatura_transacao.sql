-- V2: Faturas de cartão e transações (compras, estornos, Pix, boletos...)
-- =====================================================================

-- ---------------------------------------------------------------------
-- FATURA
-- Fatura de uma conta de cartão de crédito.
-- As faturas fechadas vêm da Pluggy com o total oficial do banco.
-- A fatura aberta ainda não existe na Pluggy (pluggy_bill_id vazio).
-- ---------------------------------------------------------------------
CREATE TABLE fatura (
    id                BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id          BIGINT         NOT NULL,
    pluggy_bill_id    VARCHAR(64),
    data_fechamento   DATE,
    data_vencimento   DATE           NOT NULL,
    total_oficial     NUMERIC(14, 2),
    pagamento_minimo  NUMERIC(14, 2),
    encargos          NUMERIC(14, 2) NOT NULL DEFAULT 0,
    status            VARCHAR(20)    NOT NULL DEFAULT 'ABERTA',
    criado_em         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    atualizado_em     TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT fk_fatura_conta FOREIGN KEY (conta_id) REFERENCES conta (id),
    CONSTRAINT uk_fatura_pluggy_bill UNIQUE (pluggy_bill_id)
);

CREATE INDEX idx_fatura_conta_vencimento ON fatura (conta_id, data_vencimento);

COMMENT ON COLUMN fatura.total_oficial IS 'Total da fatura informado pelo banco (totalAmount da Pluggy). Vazio na fatura aberta';
COMMENT ON COLUMN fatura.encargos IS 'Soma de juros, IOF e tarifas da fatura (financeCharges da Pluggy)';
COMMENT ON COLUMN fatura.status IS 'ABERTA, FECHADA ou PAGA';

-- ---------------------------------------------------------------------
-- TRANSACAO
-- Todo lançamento vindo da Pluggy: compras no cartão, estornos,
-- pagamentos de fatura, tarifas, Pix, boletos, débitos...
-- ---------------------------------------------------------------------
CREATE TABLE transacao (
    id                     BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pluggy_transaction_id  VARCHAR(64)    NOT NULL,
    conta_id               BIGINT         NOT NULL,
    cartao_id              BIGINT,
    fatura_id              BIGINT,

    -- Quando aconteceu e quanto
    data_transacao         TIMESTAMPTZ    NOT NULL,
    data_compra            TIMESTAMPTZ,
    valor                  NUMERIC(14, 2) NOT NULL,
    moeda                  VARCHAR(3)     NOT NULL DEFAULT 'BRL',
    tipo_movimento         VARCHAR(10)    NOT NULL,
    status                 VARCHAR(20)    NOT NULL,

    -- Parcelamento
    parcela_numero         SMALLINT,
    parcela_total          SMALLINT,

    -- Descrição: a do banco (fixa) e a amigável (editável)
    descricao_banco        VARCHAR(255)   NOT NULL,
    descricao              VARCHAR(255),
    origem_descricao       VARCHAR(20)    NOT NULL DEFAULT 'BANCO',

    -- Destino: de quem é a compra
    pessoa_id              BIGINT,
    origem_pessoa          VARCHAR(20),

    -- Dados do estabelecimento e da operação (vindos da Pluggy)
    categoria_pluggy       VARCHAR(100),
    categoria_pluggy_id    VARCHAR(20),
    operacao_pluggy        VARCHAR(40),
    cnpj                   VARCHAR(14),
    merchant_nome          VARCHAR(150),
    mcc                    INTEGER,
    contraparte_nome       VARCHAR(150),

    -- Classificação
    tipo_lancamento        VARCHAR(30)    NOT NULL DEFAULT 'NAO_CLASSIFICADO',
    conta_nos_gastos       BOOLEAN        NOT NULL DEFAULT TRUE,

    observacao             VARCHAR(500),
    criado_em              TIMESTAMPTZ    NOT NULL DEFAULT now(),
    atualizado_em          TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT uk_transacao_pluggy UNIQUE (pluggy_transaction_id),
    CONSTRAINT fk_transacao_conta FOREIGN KEY (conta_id) REFERENCES conta (id),
    CONSTRAINT fk_transacao_cartao FOREIGN KEY (cartao_id) REFERENCES cartao (id),
    CONSTRAINT fk_transacao_fatura FOREIGN KEY (fatura_id) REFERENCES fatura (id),
    CONSTRAINT fk_transacao_pessoa FOREIGN KEY (pessoa_id) REFERENCES pessoa (id),
    CONSTRAINT ck_transacao_parcela CHECK (
        (parcela_numero IS NULL AND parcela_total IS NULL)
        OR (parcela_total >= 1 AND parcela_numero BETWEEN 1 AND parcela_total)
    ),
    CONSTRAINT ck_transacao_cnpj CHECK (cnpj IS NULL OR cnpj ~ '^[0-9]{14}$')
);

-- Índices para as consultas mais comuns: por conta e período,
-- por fatura, por pessoa e por cartão.
CREATE INDEX idx_transacao_conta_data ON transacao (conta_id, data_transacao);
CREATE INDEX idx_transacao_fatura ON transacao (fatura_id);
CREATE INDEX idx_transacao_pessoa ON transacao (pessoa_id);
CREATE INDEX idx_transacao_cartao ON transacao (cartao_id);

COMMENT ON COLUMN transacao.valor IS 'Valor como veio da Pluggy. No cartão, compras são positivas e estornos negativos';
COMMENT ON COLUMN transacao.tipo_movimento IS 'DEBITO ou CREDITO (campo type da Pluggy)';
COMMENT ON COLUMN transacao.status IS 'PENDENTE (fatura aberta) ou CONFIRMADA (lançada)';
COMMENT ON COLUMN transacao.descricao_banco IS 'Descrição original do banco. Nunca é alterada';
COMMENT ON COLUMN transacao.descricao IS 'Descrição amigável, definida por regra ou manualmente';
COMMENT ON COLUMN transacao.origem_descricao IS 'BANCO, REGRA ou MANUAL';
COMMENT ON COLUMN transacao.origem_pessoa IS 'CARTAO, CONTA, REGRA ou MANUAL';
COMMENT ON COLUMN transacao.contraparte_nome IS 'Nome de quem enviou ou recebeu um Pix/TED. Apenas o nome: documento e conta de terceiros não são guardados';
COMMENT ON COLUMN transacao.tipo_lancamento IS 'COMPRA, ESTORNO, PAGAMENTO_FATURA, TARIFA, TRANSFERENCIA_PROPRIA, RECEBIMENTO, OUTRO ou NAO_CLASSIFICADO';
COMMENT ON COLUMN transacao.conta_nos_gastos IS 'Falso para lançamentos que não são gastos, como pagamento de fatura e transferência entre contas próprias';
