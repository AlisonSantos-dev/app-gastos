-- =====================================================================
-- V11: Contas fixas
--
-- conta_fixa:     o cadastro (Sanepar, Copel, financiamento...), com o
--                 vencimento, o valor esperado e de quem é (uma pessoa
--                 ou uma divisão salva).
-- conta_fixa_mes: a conta de cada mês (a "Sanepar de novembro"), com o
--                 valor previsto, o valor pago e a situação.
-- =====================================================================

CREATE TABLE conta_fixa (
    id                BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(60)    NOT NULL,
    grupo             VARCHAR(60),
    conta_id          BIGINT,
    dia_vencimento    SMALLINT       NOT NULL,
    valor_esperado    NUMERIC(14, 2),
    pessoa_id         BIGINT,
    divisao_salva_id  BIGINT,
    chave_pagamento   VARCHAR(255),
    categoria         VARCHAR(60),
    inicio            DATE           NOT NULL,
    fim               DATE,
    ativa             BOOLEAN        NOT NULL DEFAULT TRUE,
    criado_em         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    atualizado_em     TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT uk_conta_fixa_nome UNIQUE (nome),
    CONSTRAINT fk_conta_fixa_conta FOREIGN KEY (conta_id) REFERENCES conta (id),
    CONSTRAINT fk_conta_fixa_pessoa FOREIGN KEY (pessoa_id) REFERENCES pessoa (id),
    CONSTRAINT fk_conta_fixa_divisao FOREIGN KEY (divisao_salva_id) REFERENCES divisao_salva (id),
    CONSTRAINT ck_conta_fixa_dia CHECK (dia_vencimento BETWEEN 1 AND 31),
    CONSTRAINT ck_conta_fixa_valor CHECK (valor_esperado IS NULL OR valor_esperado > 0),
    -- De quem é: uma pessoa OU uma divisão salva (exatamente um dos dois)
    CONSTRAINT ck_conta_fixa_destino CHECK ((pessoa_id IS NULL) <> (divisao_salva_id IS NULL)),
    CONSTRAINT ck_conta_fixa_vigencia CHECK (fim IS NULL OR fim >= inicio)
);

COMMENT ON COLUMN conta_fixa.grupo IS 'Agrupa as contas na tela (ex.: "Casa dos pais", "Nossa casa")';
COMMENT ON COLUMN conta_fixa.conta_id IS 'A conta corrente de onde ela costuma ser paga (usada para achar o pagamento)';
COMMENT ON COLUMN conta_fixa.valor_esperado IS 'Valor fixo (ex.: financiamento). Vazio = variável (ex.: água, luz)';
COMMENT ON COLUMN conta_fixa.chave_pagamento IS 'Trecho da descrição do pagamento no extrato (ex.: SANEPAR), já normalizado';
COMMENT ON COLUMN conta_fixa.inicio IS 'Primeiro mês (competência) em que a conta existe (sempre o dia 1)';
COMMENT ON COLUMN conta_fixa.fim IS 'Último mês, se a conta acabou (ex.: o financiamento quitado)';

CREATE TABLE conta_fixa_mes (
    id               BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_fixa_id    BIGINT         NOT NULL,
    competencia      DATE           NOT NULL,
    vencimento       DATE           NOT NULL,
    valor_previsto   NUMERIC(14, 2),
    valor_pago       NUMERIC(14, 2),
    data_pagamento   DATE,
    transacao_id     BIGINT,
    status           VARCHAR(20)    NOT NULL DEFAULT 'PENDENTE',
    observacao       VARCHAR(255),
    criado_em        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT fk_conta_mes_conta_fixa FOREIGN KEY (conta_fixa_id) REFERENCES conta_fixa (id),
    CONSTRAINT fk_conta_mes_transacao FOREIGN KEY (transacao_id) REFERENCES transacao (id),
    -- Uma conta por mês
    CONSTRAINT uk_conta_mes_competencia UNIQUE (conta_fixa_id, competencia),
    -- Um pagamento do extrato paga uma conta só
    CONSTRAINT uk_conta_mes_transacao UNIQUE (transacao_id),
    CONSTRAINT ck_conta_mes_status CHECK (status IN ('PENDENTE', 'PAGA', 'DISPENSADA')),
    CONSTRAINT ck_conta_mes_competencia CHECK (EXTRACT(DAY FROM competencia) = 1)
);

CREATE INDEX idx_conta_mes_competencia ON conta_fixa_mes (competencia);

COMMENT ON COLUMN conta_fixa_mes.competencia IS 'O mês da conta (sempre o dia 1). Competência = o mês em que ela vence';
COMMENT ON COLUMN conta_fixa_mes.transacao_id IS 'O pagamento no extrato, quando encontrado (automática ou manualmente)';
COMMENT ON COLUMN conta_fixa_mes.status IS 'PENDENTE, PAGA ou DISPENSADA (ATRASADA é calculada: pendente e vencida)';
