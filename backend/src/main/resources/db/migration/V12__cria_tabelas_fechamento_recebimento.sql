-- =====================================================================
-- V12: Fechamento do mês e recebimentos
--
-- fechamento / fechamento_item: a "foto" de um mês publicado. Cada item
--   é uma linha do total de uma pessoa (a parte dela numa compra, numa
--   conta fixa...). Depois de publicado, o mês não muda mais, mesmo que
--   uma regra ou uma divisão mude depois.
--
-- recebimento: o que cada pessoa já pagou ao titular, por mês.
-- =====================================================================

-- O titular: quem paga as faturas e recebe dos outros
ALTER TABLE pessoa ADD COLUMN titular BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE fechamento (
    id             BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competencia    DATE           NOT NULL,
    publicado_em   TIMESTAMPTZ    NOT NULL,
    total          NUMERIC(14, 2) NOT NULL,

    CONSTRAINT uk_fechamento_competencia UNIQUE (competencia),
    CONSTRAINT ck_fechamento_competencia CHECK (EXTRACT(DAY FROM competencia) = 1)
);

CREATE TABLE fechamento_item (
    id                 BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fechamento_id      BIGINT         NOT NULL,
    pessoa_id          BIGINT,
    origem             VARCHAR(20)    NOT NULL,
    -- Só os ids, sem chave estrangeira: a foto do mês continua inteira
    -- mesmo se a transação original for removida (ex.: pendente cancelada)
    transacao_id       BIGINT,
    conta_fixa_mes_id  BIGINT,
    data               DATE           NOT NULL,
    descricao          VARCHAR(255)   NOT NULL,
    detalhe            VARCHAR(100),
    valor              NUMERIC(14, 2) NOT NULL,
    valor_total        NUMERIC(14, 2) NOT NULL,
    dividida           BOOLEAN        NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_item_fechamento FOREIGN KEY (fechamento_id) REFERENCES fechamento (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_pessoa FOREIGN KEY (pessoa_id) REFERENCES pessoa (id),
    CONSTRAINT ck_item_origem CHECK (origem IN ('CARTAO', 'CONTA_CORRENTE', 'CONTA_FIXA'))
);

CREATE INDEX idx_item_fechamento ON fechamento_item (fechamento_id);
CREATE INDEX idx_item_pessoa ON fechamento_item (pessoa_id);

COMMENT ON COLUMN fechamento_item.pessoa_id IS 'Vazio = sem dono (só acontece se o mês foi publicado forçando)';
COMMENT ON COLUMN fechamento_item.valor IS 'A parte desta pessoa';
COMMENT ON COLUMN fechamento_item.valor_total IS 'O valor inteiro da compra ou da conta (igual ao valor, se não for dividida)';

CREATE TABLE recebimento (
    id            BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pessoa_id     BIGINT         NOT NULL,
    competencia   DATE           NOT NULL,
    valor         NUMERIC(14, 2) NOT NULL,
    data          DATE           NOT NULL,
    transacao_id  BIGINT,
    observacao    VARCHAR(255),
    criado_em     TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT fk_recebimento_pessoa FOREIGN KEY (pessoa_id) REFERENCES pessoa (id),
    CONSTRAINT fk_recebimento_transacao FOREIGN KEY (transacao_id) REFERENCES transacao (id),
    -- Um Pix recebido vale para um recebimento só
    CONSTRAINT uk_recebimento_transacao UNIQUE (transacao_id),
    CONSTRAINT ck_recebimento_valor CHECK (valor > 0),
    CONSTRAINT ck_recebimento_competencia CHECK (EXTRACT(DAY FROM competencia) = 1)
);

CREATE INDEX idx_recebimento_competencia ON recebimento (competencia);

COMMENT ON COLUMN recebimento.competencia IS 'O mês que este pagamento quita (sempre o dia 1)';
COMMENT ON COLUMN recebimento.transacao_id IS 'O Pix recebido no extrato, quando veio de lá (vazio = dinheiro ou outro meio)';
